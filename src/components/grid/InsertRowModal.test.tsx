import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { InsertRowModal, isAutoGeneratedColumn } from './InsertRowModal';
import { ColumnMeta } from '../../types/db';

const mockColumns: ColumnMeta[] = [
  { name: 'id', data_type: 'uuid', nullable: false, is_primary_key: true },
  { name: 'name', data_type: 'varchar', nullable: false },
  { name: 'price', data_type: 'int', nullable: true },
];

describe('InsertRowModal', () => {
  describe('isAutoGeneratedColumn', () => {
    it('returns true for auto increment and serial columns', () => {
      expect(isAutoGeneratedColumn({ name: 'custom_id', data_type: 'serial', is_auto_increment: false, nullable: false })).toBe(true);
      expect(isAutoGeneratedColumn({ name: 'code', data_type: 'int', is_auto_increment: true, nullable: false })).toBe(true);
    });

    it('returns true for primary key id or uuid', () => {
      expect(isAutoGeneratedColumn({ name: 'id', data_type: 'int', is_primary_key: true, nullable: false })).toBe(true);
      expect(isAutoGeneratedColumn({ name: 'external_id', data_type: 'uuid', is_primary_key: true, nullable: false })).toBe(true);
    });

    it('returns true for created_at and updated_at', () => {
      expect(isAutoGeneratedColumn({ name: 'created_at', data_type: 'timestamp', nullable: false })).toBe(true);
      expect(isAutoGeneratedColumn({ name: 'updated_at', data_type: 'timestamp', nullable: false })).toBe(true);
    });

    it('does NOT mark words ending with "id" or foreign keys as auto generated', () => {
      expect(isAutoGeneratedColumn({ name: 'paid', data_type: 'boolean', nullable: false })).toBe(false);
      expect(isAutoGeneratedColumn({ name: 'valid', data_type: 'boolean', nullable: false })).toBe(false);
      expect(isAutoGeneratedColumn({ name: 'grid', data_type: 'varchar', nullable: false })).toBe(false);
      expect(isAutoGeneratedColumn({ name: 'user_id', data_type: 'int', nullable: false })).toBe(false);
      expect(isAutoGeneratedColumn({ name: 'customer_id', data_type: 'bigint', nullable: false })).toBe(false);
    });
  });
  it('does not render when isOpen is false', () => {
    const { container } = render(
      <InsertRowModal
        isOpen={false}
        onClose={vi.fn()}
        tableName="products"
        columns={mockColumns}
        onSubmit={vi.fn()}
      />
    );
    expect(container.firstChild).toBeNull();
  });

  it('renders all column fields when open', () => {
    render(
      <InsertRowModal
        isOpen={true}
        onClose={vi.fn()}
        tableName="products"
        schemaName="public"
        columns={mockColumns}
        onSubmit={vi.fn()}
      />
    );

    expect(screen.getByText(/Insert New Row/i)).toBeInTheDocument();
    expect(screen.getByText('public.products')).toBeInTheDocument();
    expect(screen.getByLabelText(/name/i)).toBeInTheDocument();
    expect(screen.getByLabelText(/price/i)).toBeInTheDocument();
  });

  it('calls onSubmit with user inputted data and converts numbers', async () => {
    const onSubmit = vi.fn().mockResolvedValue(undefined);
    const onClose = vi.fn();

    render(
      <InsertRowModal
        isOpen={true}
        onClose={onClose}
        tableName="products"
        columns={mockColumns}
        onSubmit={onSubmit}
      />
    );

    const nameInput = screen.getByPlaceholderText('Enter name...');
    fireEvent.change(nameInput, { target: { value: 'Test Product' } });

    const priceInput = screen.getByPlaceholderText('Enter price...');
    fireEvent.change(priceInput, { target: { value: '150' } });

    const submitBtn = screen.getByRole('button', { name: /Insert Row/i });
    fireEvent.click(submitBtn);

    expect(onSubmit).toHaveBeenCalledWith({
      id: null,
      name: 'Test Product',
      price: 150,
    });
  });

  it('calls onClose when Cancel button is clicked', () => {
    const onClose = vi.fn();
    render(
      <InsertRowModal
        isOpen={true}
        onClose={onClose}
        tableName="products"
        columns={mockColumns}
        onSubmit={vi.fn()}
      />
    );

    const cancelBtn = screen.getByRole('button', { name: /Cancel/i });
    fireEvent.click(cancelBtn);
    expect(onClose).toHaveBeenCalled();
  });

  it('displays message when columns list is empty and disables submit button', () => {
    render(
      <InsertRowModal
        isOpen={true}
        onClose={vi.fn()}
        tableName="test_data"
        columns={[]}
        onSubmit={vi.fn()}
      />
    );

    expect(screen.getByText('No columns found for this table.')).toBeInTheDocument();
    const submitBtn = screen.getByRole('button', { name: /Insert Row/i });
    expect(submitBtn).toBeDisabled();
  });

  it('preserves precision for BIGINT exceeding safe integer and decimal strings', async () => {
    const onSubmit = vi.fn().mockResolvedValue(undefined);
    const testColumns: ColumnMeta[] = [
      { name: 'big_id', data_type: 'bigint', nullable: false },
      { name: 'amount', data_type: 'decimal', nullable: false },
      { name: 'ratio', data_type: 'float', nullable: false },
    ];

    render(
      <InsertRowModal
        isOpen={true}
        onClose={vi.fn()}
        tableName="accounts"
        columns={testColumns}
        onSubmit={onSubmit}
      />
    );

    const bigIdInput = screen.getByPlaceholderText('Enter big_id...');
    fireEvent.change(bigIdInput, { target: { value: '9007199254740999999' } });

    const amountInput = screen.getByPlaceholderText('Enter amount...');
    fireEvent.change(amountInput, { target: { value: '123456789.987654321' } });

    const ratioInput = screen.getByPlaceholderText('Enter ratio...');
    fireEvent.change(ratioInput, { target: { value: '0.125' } });

    const submitBtn = screen.getByRole('button', { name: /Insert Row/i });
    fireEvent.click(submitBtn);

    expect(onSubmit).toHaveBeenCalledWith({
      big_id: '9007199254740999999', // Kept as string because it exceeds Number.MAX_SAFE_INTEGER
      amount: '123456789.987654321', // Kept as string for decimal
      ratio: 0.125, // Converted to number for float
    });
  });
});
